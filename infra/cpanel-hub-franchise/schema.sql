CREATE TABLE IF NOT EXISTS hub_franchise_applications (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    mobile_number VARCHAR(32) NOT NULL,
    whatsapp_number VARCHAR(32) NOT NULL DEFAULT '',
    email VARCHAR(254) NOT NULL,
    residential_district VARCHAR(64) NOT NULL,
    preferred_district VARCHAR(64) NOT NULL,
    first_preferred_hub VARCHAR(100) NOT NULL,
    second_preferred_hub VARCHAR(100) NOT NULL DEFAULT '',
    total_investment VARCHAR(64) NOT NULL,
    funds_available VARCHAR(64) NOT NULL,
    suitable_premises VARCHAR(64) NOT NULL,
    floor_area VARCHAR(64) NOT NULL,
    score_total TINYINT UNSIGNED NOT NULL DEFAULT 0,
    score_breakdown JSON NOT NULL,
    tier VARCHAR(4) NOT NULL DEFAULT 'C',
    selection_stage TINYINT UNSIGNED NOT NULL DEFAULT 1,
    payload_json LONGTEXT NOT NULL,
    fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    received_at DATETIME NOT NULL,
    INDEX hub_apps_received_at (received_at),
    INDEX hub_apps_tier (tier),
    INDEX hub_apps_district (preferred_district)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
